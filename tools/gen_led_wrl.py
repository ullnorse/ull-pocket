"""Writes lib/ull-pocket.3dshapes/LED_XL-1606_SideView.wrl: XINGLIGHT XL-1606 side-view LED lying on the board
(datasheet p.7): 1.7 wide, 0.6 tall, 0.48 deep substrate with end terminals, 1.2-1.4 wide lens 0.62 deep.
Footprint frame (mm, y down): pads at y -0.75..0.20, substrate y -0.28..0.20, lens to y +0.82 (toward the board edge).
Cathode mark (green) on the back face at the pad 1 (cathode, +x) end. VRML units are 2.54 mm, y up."""
import os
U = 2.54
def box(x0, x1, y0, y1, z0, z1, col, tr=0.0):
    # mm in footprint frame (y down) -> VRML (y up)
    p = [(x, -y, z) for z in (z0, z1) for (x, y) in ((x0, y0), (x1, y0), (x1, y1), (x0, y1))]
    pts = ", ".join("%.4f %.4f %.4f" % (x / U, y / U, z / U) for x, y, z in p)
    return ("Shape { appearance Appearance { material Material { diffuseColor %s specularColor 0.3 0.3 0.3 shininess 0.4 transparency %.1f } }\n"
            " geometry IndexedFaceSet { coord Coordinate { point [ %s ] } coordIndex [ 0,1,2,3,-1,4,7,6,5,-1,0,4,5,1,-1,1,5,6,2,-1,2,6,7,3,-1,3,7,4,0,-1 ] } }\n" % (col, tr, pts))
W, Y0, Y1, L, H = 0.85, -0.28, 0.20, 0.82, 0.6
s = "#VRML V2.0 utf8\n# XINGLIGHT XL-1606 side-view LED lying flat: 1.7 x 1.1 x 0.6 mm, lens toward +y (footprint frame); generated by tools/gen_led_wrl.py\n"
s += box(-W + 0.15, W - 0.15, Y0, Y1, 0, H, "0.92 0.92 0.88")                 # substrate
s += box(-W, -W + 0.15, Y0, Y1, 0, H, "0.85 0.75 0.4")                       # terminal 2 (anode, -x)
s += box(W - 0.15, W, Y0, Y1, 0, H, "0.85 0.75 0.4")                         # terminal 1 (cathode, +x)
s += box(-0.65, 0.65, Y1, Y1 + 0.05, 0, H, "0.85 0.9 0.95", 0.2)            # lens base
s += box(-0.6, 0.6, Y1 + 0.05, L, 0.02, H - 0.02, "0.85 0.9 0.95", 0.2)       # lens
s += box(0.30, 0.42, Y0 - 0.01, Y0, 0.05, H - 0.05, "0.2 0.8 0.3")             # cathode mark, back face
open(os.path.join(os.path.dirname(__file__), "..", "lib", "ull-pocket.3dshapes", "LED_XL-1606_SideView.wrl"), "w").write(s)
